export function getSearchHint(): string {
  return SEARCH_HINTS[Math.floor(Math.random() * SEARCH_HINTS.length)];
}

export function getBreadcrumbsForList() {
  return [
    { label: 'Home', href: '/' },
    { label: 'Use Cases', current: true },
  ];
}

export function getBreadcrumbsForDetail(slug: string, title: string, category: string, categoryTitle: string) {
  return [
    { label: 'Home', href: '/' },
    { label: 'Use Cases', href: '/use-cases' },
    { label: categoryTitle || category, href: `/use-cases?category=${category}` },
    { label: title, current: true },
  ];
}

