"""Mobile device and push-token registry.

One row per (tenant, user, platform, device id). The device id is generated by the
app and is stable across reinstalls on iOS only if the app stores it in the keychain,
so this table tolerates the same person having several rows — what it does not
tolerate is two people sharing a row, which is why the uniqueness is scoped by both
tenant and user.

Push tokens are per device *and* per platform, and they rotate: FCM and APNs both
issue a new token after a reinstall, a restore, or an OS update. So a device can
hold an old (inactive) token and a new one, and a send fan-outs to the active ones
only. Tokens are never returned by any API: the console sees a hint (last six
characters) and a failure count, which is enough to answer "is this device still
receiving anything?" without handing out push credentials.

Quiet hours are per device, bounded by ``PUSH_QUIET_HOURS_MAX_SPAN`` (12h default) so
a tenant cannot configure "never notify me" and then report undelivered pages as an
incident. Window semantics: half-open, ``[start, end)`` in the device's own timezone,
and a window whose end is before its start crosses midnight — which is the common
case for a 22:00–07:00 night window and the one worth getting right.
"""

from __future__ import annotations

import uuid
from datetime import datetime, time, timezone
from typing import Any
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.platform_v2_models import MobileDevice, PushToken
from app.platform_v2.errors import Conflict, NotFound, ValidationFailed
from app.platform_v2.settings import get_plat2_settings

PLATFORMS = ("ios", "android")

#: Tokens longer than this are not provider tokens; they are a client bug or an
#: attempt to store something that is not a token at all.
MAX_TOKEN_LENGTH = 4096

#: How many consecutive permanent failures before a token is deactivated.
MAX_PERMANENT_FAILURES = 3


def _now() -> datetime:
    return datetime.now(timezone.utc)


#: The platforms this deployment can send push to. Anything else is refused at the
#: edge of the system, because a device row with a made-up platform can never be
#: delivered to and would sit in the table looking like a working device.
PLATFORMS = ("ios", "android")


def validate_platform(value: str) -> str:
    """Normalise and check a platform value."""
    cleaned = (value or "").strip().lower()
    if cleaned not in PLATFORMS:
        raise ValidationFailed(
            f"platform must be one of {', '.join(PLATFORMS)}",
            detail={"platform": str(value)[:32]},
        )
    return cleaned


def token_hint(token: str) -> str:
    """The tail of a token, safe to display.

    Six characters is enough for an operator to match a row against a device log and
    not enough to reconstruct a token: FCM tokens are 150+ characters of
    cryptographically random material.
    """
    cleaned = (token or "").strip()
    if len(cleaned) <= 6:
        return "…"
    return "…" + cleaned[-6:]


def validate_token(token: str, *, platform: str) -> str:
    if platform not in PLATFORMS:
        raise ValidationFailed("platform must be ios or android", detail={"platform": platform})
    cleaned = (token or "").strip()
    if not cleaned:
        raise ValidationFailed("token is required")
    if len(cleaned) > MAX_TOKEN_LENGTH:
        raise ValidationFailed(f"token must be at most {MAX_TOKEN_LENGTH} characters")
    if any(character.isspace() for character in cleaned):
        raise ValidationFailed("token must not contain whitespace")
    # APNs tokens are hex; FCM tokens are URL-safe. Both are printable ASCII, so
    # anything else is a client bug we would rather reject than store.
    if not all(33 <= ord(character) <= 126 for character in cleaned):
        raise ValidationFailed("token must be printable ASCII")
    return cleaned


def parse_clock(value: str, *, field: str) -> time:
    try:
        hour_text, minute_text = value.split(":", 1)
        hour, minute = int(hour_text), int(minute_text)
    except Exception as exc:  # noqa: BLE001
        raise ValidationFailed(f"{field} must be HH:MM", detail={field: value}) from exc
    if not (0 <= hour <= 23 and 0 <= minute <= 59):
        raise ValidationFailed(f"{field} must be a valid time of day", detail={field: value})
    return time(hour, minute)


def validate_quiet_hours(payload: dict[str, Any] | None) -> dict[str, Any]:
    """Validate and normalise a quiet-hours window.

    Returns ``{}`` for "no quiet hours", which is different from a window of zero
    length and is stored as an empty object.
    """
    if payload is None or payload == {}:
        return {}
    if not isinstance(payload, dict):
        raise ValidationFailed("quiet_hours must be an object or null")
    unknown = sorted(set(payload) - {"start", "end", "timezone", "enabled"})
    if unknown:
        raise ValidationFailed("quiet_hours has unknown keys", detail={"unknown": unknown})
    if payload.get("enabled") is False:
        return {}

    start = parse_clock(str(payload.get("start", "")), field="quiet_hours.start")
    end = parse_clock(str(payload.get("end", "")), field="quiet_hours.end")
    zone_name = str(payload.get("timezone") or "UTC")
    try:
        ZoneInfo(zone_name)
    except ZoneInfoNotFoundError as exc:
        raise ValidationFailed("quiet_hours.timezone is not a known timezone", detail={"timezone": zone_name}) from exc

    start_minutes = start.hour * 60 + start.minute
    end_minutes = end.hour * 60 + end.minute
    if start_minutes == end_minutes:
        raise ValidationFailed("quiet_hours window must have a non-zero length")

    span_minutes = (end_minutes - start_minutes) % (24 * 60)
    ceiling = int(get_plat2_settings().push_quiet_hours_max_span) * 60
    if span_minutes > ceiling:
        raise ValidationFailed(
            f"quiet_hours window must be at most {ceiling // 60} hours",
            detail={"span_hours": round(span_minutes / 60, 2), "max_span_hours": ceiling // 60},
        )
    return {
        "start": start.strftime("%H:%M"),
        "end": end.strftime("%H:%M"),
        "timezone": zone_name,
        "enabled": True,
    }


def in_quiet_hours(quiet_hours: dict[str, Any] | None, moment: datetime | None = None) -> bool:
    """True when ``moment`` falls inside the device's quiet window.

    A window that crosses midnight (``22:00`` → ``07:00``) is handled by comparing
    minutes-since-midnight with the wrap, not by comparing timestamps — which is
    the bug that makes a night window silently stop working.
    """
    if not quiet_hours:
        return False
    try:
        start = parse_clock(str(quiet_hours.get("start")), field="start")
        end = parse_clock(str(quiet_hours.get("end")), field="end")
        zone = ZoneInfo(str(quiet_hours.get("timezone") or "UTC"))
    except (ValidationFailed, ZoneInfoNotFoundError):
        # A malformed stored window must not block notifications forever.
        return False
    instant = (moment or _now()).astimezone(zone)
    current = instant.hour * 60 + instant.minute
    start_minutes = start.hour * 60 + start.minute
    end_minutes = end.hour * 60 + end.minute
    if start_minutes < end_minutes:
        return start_minutes <= current < end_minutes
    return current >= start_minutes or current < end_minutes


async def _device_row(
    session: AsyncSession, *, tenant_id: uuid.UUID, user_id: uuid.UUID, platform: str, device_id: str
) -> MobileDevice | None:
    row = await session.execute(
        select(MobileDevice).where(
            MobileDevice.tenant_id == tenant_id,
            MobileDevice.user_id == user_id,
            MobileDevice.platform == platform,
            MobileDevice.device_id == device_id,
        )
    )
    return row.scalar_one_or_none()


async def register(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    user_id: uuid.UUID,
    platform: str,
    device_id: str,
    app_version: str = "",
    os_version: str = "",
    push_enabled: bool = True,
    quiet_hours: dict[str, Any] | None = None,
    commit: bool = False,
) -> tuple[MobileDevice, bool]:
    """Idempotent device registration. Returns ``(device, created)``.

    Re-registering an existing device updates the metadata and clears a previous
    revocation: reinstalling the app is the normal way a revoked device comes back,
    and refusing it would leave the person with a phone that never receives a rota.
    """
    if platform not in PLATFORMS:
        raise ValidationFailed("platform must be ios or android", detail={"platform": platform})
    device_id = (device_id or "").strip()
    if not device_id:
        raise ValidationFailed("device_id is required")
    if len(device_id) > 120:
        raise ValidationFailed("device_id must be at most 120 characters")
    window = validate_quiet_hours(quiet_hours)

    row = await _device_row(
        session, tenant_id=tenant_id, user_id=user_id, platform=platform, device_id=device_id
    )
    created = row is None
    if row is None:
        row = MobileDevice(
            id=uuid.uuid4(),
            tenant_id=tenant_id,
            user_id=user_id,
            platform=platform,
            device_id=device_id,
            app_version=(app_version or "")[:40],
            os_version=(os_version or "")[:40],
            push_enabled=bool(push_enabled),
            quiet_hours=window,
            last_seen_at=_now(),
        )
        session.add(row)
    else:
        row.app_version = (app_version or row.app_version)[:40]
        row.os_version = (os_version or row.os_version)[:40]
        row.push_enabled = bool(push_enabled)
        if quiet_hours is not None:
            row.quiet_hours = window
        row.last_seen_at = _now()
        row.revoked_at = None
    await session.flush()
    if commit:
        await session.commit()
    return row, created


async def get(session: AsyncSession, *, tenant_id: uuid.UUID, user_id: uuid.UUID, device_pk: uuid.UUID) -> MobileDevice:
    row = await session.execute(
        select(MobileDevice).where(
            MobileDevice.id == device_pk,
            MobileDevice.tenant_id == tenant_id,
            MobileDevice.user_id == user_id,
        )
    )
    found = row.scalar_one_or_none()
    if found is None:
        raise NotFound("device not found")
    return found


async def list_for_user(session: AsyncSession, *, tenant_id: uuid.UUID, user_id: uuid.UUID) -> list[MobileDevice]:
    rows = await session.execute(
        select(MobileDevice)
        .where(MobileDevice.tenant_id == tenant_id, MobileDevice.user_id == user_id)
        .order_by(MobileDevice.last_seen_at.desc())
    )
    return list(rows.scalars().all())


async def update_quiet_hours(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    user_id: uuid.UUID,
    device_pk: uuid.UUID,
    quiet_hours: dict[str, Any] | None,
    commit: bool = False,
) -> MobileDevice:
    row = await get(session, tenant_id=tenant_id, user_id=user_id, device_pk=device_pk)
    row.quiet_hours = validate_quiet_hours(quiet_hours)
    row.last_seen_at = _now()
    if commit:
        await session.commit()
    return row


async def set_push_enabled(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    user_id: uuid.UUID,
    device_pk: uuid.UUID,
    enabled: bool,
    commit: bool = False,
) -> MobileDevice:
    row = await get(session, tenant_id=tenant_id, user_id=user_id, device_pk=device_pk)
    row.push_enabled = bool(enabled)
    row.last_seen_at = _now()
    if commit:
        await session.commit()
    return row


async def revoke(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    user_id: uuid.UUID,
    device_pk: uuid.UUID,
    commit: bool = False,
) -> MobileDevice:
    """Revoke a device and deactivate its tokens.

    Revoking is what a person does when they lose a phone, so it must stop delivery
    immediately: the tokens are deactivated in the same transaction, not left for a
    background GC to notice.
    """
    row = await get(session, tenant_id=tenant_id, user_id=user_id, device_pk=device_pk)
    row.revoked_at = _now()
    tokens = await session.execute(
        select(PushToken).where(PushToken.device_id == row.id, PushToken.active.is_(True))
    )
    for token in tokens.scalars().all():
        token.active = False
        token.invalidated_at = _now()
        token.last_error = "device revoked"
    if commit:
        await session.commit()
    return row


async def touch(session: AsyncSession, *, device: MobileDevice) -> None:
    device.last_seen_at = _now()
    await session.flush()


async def attach_token(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    device: MobileDevice,
    token: str,
    commit: bool = False,
) -> PushToken:
    """Attach a push token to a device, deactivating any previous token.

    Only one token per device is active at a time. Keeping the old row (inactive)
    instead of deleting it means a delivery record can always be traced back to the
    token it was sent to, which is the difference between "we sent it" and "we think
    we sent it".
    """
    if device.revoked_at is not None:
        # A revoked device is a device the user removed. Re-attaching a token to it
        # would silently undo that decision.
        raise Conflict("this device has been revoked")
    cleaned = validate_token(token, platform=device.platform)
    existing = await session.execute(
        select(PushToken).where(PushToken.platform == device.platform, PushToken.token == cleaned)
    )
    current = existing.scalar_one_or_none()
    previous = await session.execute(
        select(PushToken).where(PushToken.device_id == device.id, PushToken.active.is_(True))
    )
    for token_row in previous.scalars().all():
        if current is not None and token_row.id == current.id:
            continue
        token_row.active = False
        token_row.invalidated_at = _now()
        token_row.last_error = "superseded by a newer token"

    if current is not None:
        if current.device_id != device.id:
            # The same token on another device means the app was reinstalled on a
            # new phone with the same token: it belongs to the newest device.
            current.device_id = device.id
            current.tenant_id = tenant_id
        current.active = True
        current.invalidated_at = None
        current.last_error = ""
        current.failure_count = 0
        row = current
    else:
        row = PushToken(
            id=uuid.uuid4(),
            tenant_id=tenant_id,
            device_id=device.id,
            platform=device.platform,
            token=cleaned,
            token_hint=token_hint(cleaned),
            active=True,
        )
        session.add(row)
    await session.flush()
    if commit:
        await session.commit()
    return row


async def detach_token(
    session: AsyncSession, *, tenant_id: uuid.UUID, device: MobileDevice, commit: bool = False
) -> int:
    rows = await session.execute(
        select(PushToken).where(
            PushToken.tenant_id == tenant_id, PushToken.device_id == device.id, PushToken.active.is_(True)
        )
    )
    deactivated = 0
    for row in rows.scalars().all():
        row.active = False
        row.invalidated_at = _now()
        row.last_error = "detached"
        deactivated += 1
    if commit:
        await session.commit()
    return deactivated


async def active_tokens(session: AsyncSession, *, tenant_id: uuid.UUID, device: MobileDevice) -> list[PushToken]:
    rows = await session.execute(
        select(PushToken).where(
            PushToken.tenant_id == tenant_id, PushToken.device_id == device.id, PushToken.active.is_(True)
        )
    )
    return list(rows.scalars().all())


async def record_failure(
    session: AsyncSession, *, token: PushToken, error: str, permanent: bool
) -> bool:
    """Record a send failure. Returns True when the token was deactivated.

    A permanent failure (``UNREGISTERED``/``BadDeviceToken``) is trustworthy the
    first time; a transient one is not. Only permanent failures count toward
    ``MAX_PERMANENT_FAILURES``, and a single confirmation is usually enough — three
    is what protects against a provider hiccup that mislabels a token.
    """
    token.failure_count = int(token.failure_count or 0) + 1
    token.last_error = (error or "")[:200]
    if permanent and token.failure_count >= MAX_PERMANENT_FAILURES:
        token.active = False
        token.invalidated_at = _now()
        return True
    return False


async def record_success(session: AsyncSession, *, token: PushToken) -> None:
    token.failure_count = 0
    token.last_error = ""


async def purge_stale(
    session: AsyncSession, *, tenant_id: uuid.UUID, older_than_days: int | None = None, commit: bool = False
) -> int:
    """Deactivate tokens on devices that have not been seen for a long time.

    Returns the number of tokens deactivated. The device rows stay: the audit trail
    of "this person had a phone registered" is useful, and deleting rows because
    they are old is how a support investigation loses its evidence.
    """
    cfg = get_plat2_settings()
    days = int(older_than_days if older_than_days is not None else cfg.push_token_gc_days)
    cutoff = _now() - __import__("datetime").timedelta(days=days)
    rows = await session.execute(
        select(PushToken)
        .join(MobileDevice, MobileDevice.id == PushToken.device_id)
        .where(
            PushToken.tenant_id == tenant_id,
            PushToken.active.is_(True),
            MobileDevice.last_seen_at < cutoff,
        )
    )
    deactivated = 0
    for token in rows.scalars().all():
        token.active = False
        token.invalidated_at = _now()
        token.last_error = f"device unseen for {days} days"
        deactivated += 1
    if commit:
        await session.commit()
    return deactivated


def describe(row: MobileDevice, tokens: list[PushToken] | None = None) -> dict[str, Any]:
    """Serialise a device. Token values never appear here."""
    return {
        "id": str(row.id),
        "user_id": str(row.user_id),
        "platform": row.platform,
        "device_id": row.device_id,
        "app_version": row.app_version,
        "os_version": row.os_version,
        "push_enabled": row.push_enabled,
        "quiet_hours": row.quiet_hours or {},
        "last_seen_at": row.last_seen_at.isoformat() if row.last_seen_at else None,
        "revoked_at": row.revoked_at.isoformat() if row.revoked_at else None,
        "created_at": row.created_at.isoformat() if row.created_at else None,
        "tokens": [describe_token(token) for token in (tokens or [])],
    }


def describe_token(token: PushToken) -> dict[str, Any]:
    return {
        "id": str(token.id),
        "platform": token.platform,
        "hint": token.token_hint,
        "active": token.active,
        "failure_count": token.failure_count,
        "last_error": token.last_error,
        "invalidated_at": token.invalidated_at.isoformat() if token.invalidated_at else None,
    }


