func main() {
  logrus.Info("VoxDesk Real-time Engine starting — Go version — 10-25MB, 10K-20K lines")
  cfg := config.Load()
  engine := concurrency.NewEngine(cfg)
  wsServer := websocket.NewServer(cfg, engine)
  voiceHandler := voice.NewHandler(cfg, engine)
  webrtcHandler := webrtc.NewHandler(cfg, engine)
  livekitHandler := livekit.NewHandler(cfg, engine)
  streamHandler := stream.NewHandler(cfg, engine)
  go wsServer.Start()
  go voiceHandler.Start()
  go webrtcHandler.Start()
  go livekitHandler.Start()
  go streamHandler.Start()
  go metrics.Start(cfg)
  go health.Start(cfg)
  sigChan := make(chan os.Signal, 1)
  signal.Notify(sigChan, syscall.SIGINT, syscall.SIGTERM)
  <-sigChan
  logrus.Info("Shutting down gracefully")
  engine.Shutdown()
}
