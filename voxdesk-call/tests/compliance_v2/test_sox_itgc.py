"""ITGC coverage: the general controls a financial audit asks about.

An IT general-control review asks three questions — who can get in, how changes
reach production, and whether operations are watched. This deployment evidences
those areas through the SOC 2 control matrix rather than a second, parallel set
of "SOX" documents: a change-management control and a logical-access control are
the same control whichever framework names them.

Nothing here asserts a financial-statement audit outcome, and the tests actively
refuse the vocabulary of one. What is proven is that each ITGC area resolves to
real controls, that every control in the matrix has a collector, and that the
collector set and the document cannot drift apart silently.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from app.compliance_v2.soc2 import control_map
from app.compliance_v2.soc2.runner import build_collectors

ROOT = Path(__file__).resolve().parents[2]

#: ITGC area -> the control family that evidences it.
ITGC_AREAS = {
    "logical_access": ("CC6.1", "CC6.2", "CC6.3"),
    "change_management": ("CC7.1", "CC7.2"),
    "operations_monitoring": ("CC7.3", "A1.1", "PI1.1", "PI1.4"),
    "data_integrity": ("PI1.1", "PI1.4", "C1.1"),
}


@pytest.fixture(scope="module")
def matrix():
    loaded = control_map.load_control_map(ROOT)
    assert loaded.document_present, "the control matrix document must exist"
    return loaded


def test_every_itgc_area_resolves_to_controls_in_the_matrix(matrix):
    for area, family in ITGC_AREAS.items():
        covered = [control for control in family if control in matrix.controls]
        assert covered, f"{area} maps to no control in the matrix"


def test_every_control_in_the_matrix_has_a_collector(matrix):
    owners = {control: matrix.collector_for(control) for control in matrix.ids}

    assert all(owners.values()), f"unowned controls: {sorted(c for c, o in owners.items() if not o)}"
    assert set(owners.values()) <= set(build_collectors())


#: Controls the matrix lists as organizational evidence: a signed subprocessor
#: report is collected from a vendor, never generated by a collector. Anything
#: outside this set appearing in ``unmapped`` is real drift.
ORGANIZATIONAL_ONLY = {"CC9.2"}


def test_the_document_and_the_collectors_do_not_drift(matrix):
    assert set(matrix.unmapped) <= ORGANIZATIONAL_ONLY, (
        f"controls named by the matrix with no collector and no owner: {matrix.unmapped}"
    )


def test_each_itgc_area_is_evidenced_by_a_distinct_collector(matrix):
    by_area = {
        area: {matrix.collector_for(control) for control in family if control in matrix.controls}
        for area, family in ITGC_AREAS.items()
    }

    for area, collectors in by_area.items():
        assert collectors - {""}, f"{area} has no owning collector"


def test_the_control_matrix_is_the_only_compliance_source():
    text = control_map.find_matrix(ROOT).read_text(encoding="utf-8").lower()

    for forbidden in ("sox certified", "certified", "attestation obtained"):
        assert forbidden not in text


def test_a_matrix_naming_an_uncovered_control_is_rejected(tmp_path):
    matrix_path = tmp_path / control_map.MATRIX_PATH
    matrix_path.parent.mkdir(parents=True, exist_ok=True)
    matrix_path.write_text(
        "# Control matrix\n\n| Control | Description |\n| --- | --- |\n"
        "| **CC6.1** | logical access |\n| **CC8.1** | change management, unowned |\n",
        encoding="utf-8",
    )

    with pytest.raises(control_map.ControlMapError):
        control_map.load_control_map(tmp_path)


def test_a_missing_matrix_is_reported_as_absent_not_as_a_pass(tmp_path):
    loaded = control_map.load_control_map(tmp_path)

    assert loaded.document_present is False
    assert loaded.controls == {}
