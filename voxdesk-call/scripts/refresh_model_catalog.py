#!/usr/bin/env python3
"""Diff the model catalogue against provider model lists (P12-10).

Default behaviour touches no network: it validates the catalogue and prints what a network run
*would* fetch. ``--allow-network`` performs the fetch for providers whose key is present and
writes a YAML diff suitable for a pull request.

The script never edits the catalogue. A human reads the diff and decides, because a model that
silently appears in the catalogue is a model nobody has reviewed the price or capabilities of.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.agent.providers.model_catalog import (  # noqa: E402
    catalog_index,
    deprecated_models,
    validate_catalog,
)

#: Provider → (env var holding the key, endpoint that lists models).
PROVIDER_ENDPOINTS: dict[str, tuple[str, str]] = {
    "openai": ("OPENAI_API_KEY", "https://api.openai.com/v1/models"),
    "anthropic": ("ANTHROPIC_API_KEY", "https://api.anthropic.com/v1/models"),
    "deepgram": ("DEEPGRAM_API_KEY", "https://api.deepgram.com/v1/models"),
    "elevenlabs": ("ELEVENLABS_API_KEY", "https://api.elevenlabs.io/v1/models"),
}


@dataclass
class ProviderStatus:
    provider: str
    fetched: bool
    reason: str
    live_ids: list[str]
    new_ids: list[str]
    missing_ids: list[str]

    def as_dict(self) -> dict[str, object]:
        return {
            "provider": self.provider,
            "fetched": self.fetched,
            "reason": self.reason,
            "live_ids": self.live_ids,
            "new_ids": self.new_ids,
            "missing_ids": self.missing_ids,
        }


def _fetch_live_ids(provider: str, key: str, url: str) -> list[str]:
    import httpx

    headers = {"Authorization": f"Bearer {key}"}
    if provider == "anthropic":
        headers = {"x-api-key": key, "anthropic-version": "2023-06-01"}
    if provider == "deepgram":
        headers = {"Authorization": f"Token {key}"}
    with httpx.Client(timeout=20.0) as client:
        response = client.get(url, headers=headers)
        response.raise_for_status()
        payload = response.json()
    if isinstance(payload, dict):
        items = payload.get("data") or payload.get("models") or []
    else:
        items = payload
    ids: list[str] = []
    for item in items:
        if isinstance(item, str):
            ids.append(item)
        elif isinstance(item, dict):
            candidate = item.get("id") or item.get("model_id") or item.get("canonical_name")
            if candidate:
                ids.append(str(candidate))
    return sorted(set(ids))


def collect_statuses(*, allow_network: bool) -> list[ProviderStatus]:
    index = catalog_index()
    statuses: list[ProviderStatus] = []
    for provider, known in index.items():
        if provider not in PROVIDER_ENDPOINTS:
            statuses.append(
                ProviderStatus(provider, False, "no public model-list endpoint wired", [], [], [])
            )
            continue
        env_var, url = PROVIDER_ENDPOINTS[provider]
        key = (os.environ.get(env_var) or "").strip()
        if not allow_network:
            statuses.append(
                ProviderStatus(provider, False, f"dry run; would fetch {url} using {env_var}", [], [], [])
            )
            continue
        if not key:
            statuses.append(
                ProviderStatus(provider, False, f"{env_var} is not set; cannot fetch {url}", [], [], [])
            )
            continue
        try:
            live = _fetch_live_ids(provider, key, url)
        except Exception as exc:  # noqa: BLE001 - reported, never raised past the CLI
            statuses.append(ProviderStatus(provider, False, f"fetch failed: {type(exc).__name__}: {exc}", [], [], []))
            continue
        known_set = set(known)
        live_set = set(live)
        statuses.append(
            ProviderStatus(
                provider=provider,
                fetched=True,
                reason="fetched",
                live_ids=live,
                new_ids=sorted(live_set - known_set),
                missing_ids=sorted(known_set - live_set),
            )
        )
    return statuses


def render_yaml(statuses: list[ProviderStatus]) -> str:
    lines = ["# Generated by scripts/refresh_model_catalog.py — review before applying.", "providers:"]
    for status in statuses:
        lines.append(f"  {status.provider}:")
        lines.append(f"    fetched: {str(status.fetched).lower()}")
        lines.append(f"    reason: {json.dumps(status.reason)}")
        lines.append(f"    new_ids: {json.dumps(status.new_ids)}")
        lines.append(f"    missing_ids: {json.dumps(status.missing_ids)}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--allow-network", action="store_true",
                        help="actually call provider model-list endpoints (needs keys)")
    parser.add_argument("--output", type=Path, default=None, help="write the YAML diff here")
    parser.add_argument("--json", action="store_true", help="print JSON instead of YAML")
    args = parser.parse_args(argv)

    problems = validate_catalog()
    deprecated = deprecated_models()
    statuses = collect_statuses(allow_network=args.allow_network)

    if problems:
        for problem in problems:
            print(f"ERROR: {problem}", file=sys.stderr)
        return 1

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(render_yaml(statuses), encoding="utf-8")

    if args.json:
        print(json.dumps(
            {
                "catalog_valid": True,
                "deprecated": [f"{spec.provider}/{spec.model_id}" for spec in deprecated],
                "providers": [status.as_dict() for status in statuses],
            },
            indent=2,
        ))
        return 0

    print(f"catalogue valid: {len(catalog_index())} providers")
    if deprecated:
        print(f"deprecated entries: {', '.join(f'{s.provider}/{s.model_id}' for s in deprecated)}")
    for status in statuses:
        marker = "fetched" if status.fetched else "skipped"
        print(f"  {status.provider:<12} {marker:<8} {status.reason}")
        if status.new_ids:
            print(f"      new:     {', '.join(status.new_ids)}")
        if status.missing_ids:
            print(f"      missing: {', '.join(status.missing_ids)}")
    if not args.allow_network:
        print("dry run: pass --allow-network (with provider keys) to fetch live model lists")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
