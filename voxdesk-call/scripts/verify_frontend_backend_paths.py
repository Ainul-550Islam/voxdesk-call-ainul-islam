#!/usr/bin/env python3
"""Fail the build when the frontend calls an API path the backend does not serve.

Every other contract check in this repository compares two files that were both
generated by us. This one compares the dashboard source against the *live*
FastAPI application: it imports ``app.main`` and reads ``app.openapi()``, so a
route that was renamed, never mounted, or mounted under a different prefix is
caught the moment the code changes, with no snapshot to drift out of date.

That is the whole reason this exists. A dashboard pointing at a path the server
does not have is a button that silently does nothing in production, and no
amount of unit-testing the frontend will catch it — the frontend is correct, the
contract is not.

Usage:
    python3 scripts/verify_frontend_backend_paths.py
    python3 scripts/verify_frontend_backend_paths.py --json-out reports/check/fe_be.json
    python3 scripts/verify_frontend_backend_paths.py --allowlist path/one path/two

Exit code 0 when every extracted path is served, 1 otherwise. The allowlist is
empty by default and is a deliberate escape hatch, not a standing one: every
entry in it is a known lie the code is telling, and it should shrink to zero.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Iterator

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

BLOCK_COMMENT_RE = re.compile(r"/\*[\s\S]*?\*/")
LINE_COMMENT_RE = re.compile(r"(?<!:)//.*$")

#: Directories and file shapes that are not shipping dashboard code.
SKIP_DIR_NAMES = frozenset(
    {"node_modules", ".next", "dist", "build", "coverage", "__snapshots__", ".turbo"}
)
SKIP_SUFFIXES = (".test.ts", ".test.tsx", ".spec.ts", ".spec.tsx")
SKIP_PARTS = frozenset({"__tests__", "__mocks__", "tests", "test"})

#: Only server API paths are checked. A page route (``/dashboard/calls``) or a
#: static asset is not part of this contract.
API_PREFIXES = ("/api",)

#: Paths that are prefixes or documentation examples rather than real calls.
IGNORED_VALUES = frozenset({"/api", "/api/", "/api/v1", "/api/v1/"})

QUOTE_CHARS = "\"'`"


def iter_source_files() -> list[Path]:
    """Every shipping TypeScript source file in either dashboard."""
    roots = [ROOT / "dashboard" / "src", ROOT / "dashboard-next"]
    found: list[Path] = []
    for root in roots:
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*")):
            if not path.is_file() or path.suffix.lower() not in {".ts", ".tsx"}:
                continue
            if any(part in SKIP_DIR_NAMES for part in path.parts):
                continue
            # Declaration files describe types, they do not issue requests.
            if path.name.endswith(".d.ts"):
                continue
            if any(part in SKIP_PARTS for part in path.relative_to(root).parts):
                continue
            if path.name.endswith(SKIP_SUFFIXES):
                continue
            found.append(path)
    return found


def strip_comments(text: str) -> str:
    """Blank out comments, preserving line numbering.

    Line numbers are the only thing that makes a failure actionable, so
    comments are replaced with whitespace rather than deleted.
    """
    without_blocks = BLOCK_COMMENT_RE.sub(lambda m: "\n" * m.group(0).count("\n"), text)
    return "\n".join(LINE_COMMENT_RE.sub("", line) for line in without_blocks.splitlines())


def iter_quoted_strings(line: str) -> Iterator[tuple[int, str, str]]:
    """Yield ``(start_column, quote_char, value)`` for every string literal.

    Template literals are handled explicitly: a ``${...}`` interpolation is
    skipped as a unit, including any nested quotes inside it, because a path is
    built from the literal parts and the interpolations are exactly what gets
    normalized away later.
    """
    index = 0
    length = len(line)
    while index < length:
        char = line[index]
        if char not in QUOTE_CHARS:
            index += 1
            continue
        cursor = index + 1
        while cursor < length:
            current = line[cursor]
            if current == "\\":
                cursor += 2
                continue
            if char == "`" and line.startswith("${", cursor):
                depth = 1
                cursor += 2
                while cursor < length and depth > 0:
                    nested = line[cursor]
                    if nested == "{":
                        depth += 1
                    elif nested == "}":
                        depth -= 1
                    elif nested in QUOTE_CHARS:
                        cursor += 1
                        while cursor < length and line[cursor] != nested:
                            if line[cursor] == "\\":
                                cursor += 1
                            cursor += 1
                    cursor += 1
                continue
            if current == char:
                break
            cursor += 1
        yield index, char, line[index + 1 : cursor]
        index = cursor + 1


def extract_api_paths(text: str) -> list[tuple[int, str]]:
    """Every API path literal in one file, with its line number."""
    results: list[tuple[int, str]] = []
    for line_no, line in enumerate(text.splitlines(), 1):
        for _column, _quote, value in iter_quoted_strings(line):
            value = value.strip()
            if value in IGNORED_VALUES:
                continue
            if not value.startswith(API_PREFIXES):
                continue
            # A bare prefix with no path segment is not a callable endpoint.
            if value.rstrip("/") in IGNORED_VALUES:
                continue
            results.append((line_no, value))
    return results


#: A trailing interpolation that builds a *query string* rather than a path
#: segment — ``${qs}``, ``${q ? `?${q}` : ""}``, ``${search}``. It is not part
#: of routing, so it is dropped rather than turned into a ``{}`` placeholder
#: that would never match a route.
#:
#: The content test is "does it contain a ``?``", because that is what these
#: ternaries all reduce to once nested strings are stripped, plus the short
#: names used when the query string is built on the line above.
QUERY_SUFFIX_RE = re.compile(
    r"\$\{[^{}]*\?[\s\S]*\}$|\$\{(?:q|qs|query|suffix|search|params)\b[\s\S]*\}$"
)


def _strip_url_suffix(value: str) -> str:
    """Drop a query/fragment only when it is outside ``${...}``.

    A path interpolation can itself contain a string such as ``"?"`` or
    ``"#"``. Splitting the raw template at those characters would truncate the
    route and could compare it with an unrelated endpoint.
    """
    index = 0
    depth = 0
    while index < len(value):
        if value.startswith("${", index):
            depth += 1
            index += 2
            continue
        char = value[index]
        if depth:
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
        elif char in "?#":
            return value[:index]
        index += 1
    return value


def normalize_path(value: str) -> str:
    """Collapse a requested path and a route path to a comparable shape.

    ``/api/calls/{}`` is the same contract whether the frontend wrote it as
    ``/api/calls/${callId}``, ``/api/calls/{call_id}`` or ``/api/calls/:id``.
    The query string is dropped because it is not part of routing.
    """
    # Nullish coalescing inside an id expression is not a URL query marker.
    # Protect it before applying the legacy trailing-query shortcut below.
    value = value.replace("??", "\0")
    value = QUERY_SUFFIX_RE.sub("", value)
    value = _strip_url_suffix(value)
    out: list[str] = []
    index = 0
    length = len(value)
    while index < length:
        char = value[index]
        if value.startswith("${", index):
            depth = 1
            index += 2
            while index < length and depth > 0:
                if value[index] == "{":
                    depth += 1
                elif value[index] == "}":
                    depth -= 1
                index += 1
            out.append("{}")
            continue
        if char == "{":
            end = value.find("}", index)
            if end == -1:
                out.append(char)
                index += 1
                continue
            out.append("{}")
            index = end + 1
            continue
        if char == ":" and len(out) and out[-1] == "/":
            match = re.match(r"[A-Za-z_]\w*", value[index + 1 :])
            if match:
                out.append("{}")
                index += 1 + match.end()
                continue
        out.append(char)
        index += 1
    normalized = "".join(out)
    normalized = re.sub(r"/{2,}", "/", normalized)
    if len(normalized) > 1:
        normalized = normalized.rstrip("/")
    return normalized or "/"


def load_backend_paths() -> tuple[dict[str, set[str]], int]:
    """Route paths served by the live application, normalized and method-keyed.

    The published OpenAPI document is the starting point, but it is not the
    whole truth: a router mounted with ``include_in_schema=False`` is still
    reachable over HTTP while being absent from the schema. Those routes are
    added from ``app.routes`` so a dashboard call to one of them is reported as
    served rather than as a contract violation. The alternative — allowlisting
    the path — would hide a real, working endpoint, and this check exists to
    compare the frontend against what the server actually answers.
    """
    from app.main import app

    spec = app.openapi()
    routes: dict[str, set[str]] = {}
    for path, operations in (spec.get("paths") or {}).items():
        methods = {
            str(method).upper()
            for method in (operations or {}).keys()
            if str(method).upper() in {"GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"}
        }
        key = normalize_path(path)
        routes.setdefault(key, set()).update(methods)

    for route in app.routes:
        path = getattr(route, "path", None)
        method = getattr(route, "methods", None)
        if not path or not method:
            continue
        key = normalize_path(str(path))
        known = routes.setdefault(key, set())
        known.update(str(item).upper() for item in method)
    return routes, len(spec.get("paths") or {})


def dynamic_prefix_hits(normalized: str, backend: dict[str, set[str]]) -> list[str]:
    """Routes that could serve a path whose final segment is built at runtime.

    ``/api/cc2/softphone/calls/{callId}/${action}`` normalizes to
    ``/api/cc2/softphone/calls/{}/{}``, and the server's real routes are
    ``.../hold``, ``.../mute`` and so on. There is no way to know from the
    literal which of them the caller will pick, so the check becomes "does the
    server serve *anything* one level under this prefix". That is not a weaker
    check, it is the only check that is possible — and the concrete routes are
    returned so a reviewer can confirm the caller's action values.
    """
    parts = normalized.split("/")
    if len(parts) < 3 or parts[-1] != "{}":
        return []
    prefix = "/".join(parts[:-1])
    return sorted(
        route
        for route in backend
        if route.startswith(prefix + "/") and route.count("/") == len(parts) - 1
    )


def scan(allowlist: set[str]) -> dict[str, Any]:
    backend, backend_count = load_backend_paths()
    files = iter_source_files()

    matches: list[dict[str, Any]] = []
    dynamic: list[dict[str, Any]] = []
    unmatched: list[dict[str, Any]] = []
    allowed: list[dict[str, Any]] = []

    for path in files:
        relative = str(path.relative_to(ROOT))
        text = strip_comments(path.read_text(encoding="utf-8", errors="replace"))
        seen: set[tuple[int, str]] = set()
        for line_no, raw in extract_api_paths(text):
            if (line_no, raw) in seen:
                continue
            seen.add((line_no, raw))
            normalized = normalize_path(raw)
            entry = {
                "file": relative,
                "line": line_no,
                "path": raw,
                "normalized": normalized,
            }
            if normalized in backend:
                entry["methods"] = sorted(backend[normalized])
                matches.append(entry)
                continue
            if normalized in allowlist:
                allowed.append(entry)
                continue
            # A path whose last segment is chosen at runtime (``${action}``)
            # cannot be resolved to one route statically. It is only accepted
            # when the server really does serve concrete routes under that
            # prefix, and those routes are listed so the reader can check the
            # values the caller actually passes.
            prefix_hits = dynamic_prefix_hits(normalized, backend)
            if prefix_hits:
                entry["resolved_to"] = prefix_hits
                entry["methods"] = sorted(
                    {m for hit in prefix_hits for m in backend.get(hit, set())}
                )
                dynamic.append(entry)
                continue
            unmatched.append(entry)

    return {
        "status": "PASS" if not unmatched else "FAIL",
        "backend_paths_loaded": backend_count,
        "backend_paths_normalized": len(backend),
        "frontend_files_scanned": len(files),
        "matched_count": len(matches),
        "dynamic_count": len(dynamic),
        "allowlisted_count": len(allowed),
        "unmatched_count": len(unmatched),
        "matched": matches,
        "dynamic": dynamic,
        "unmatched": unmatched,
        "allowlisted": allowed,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--allowlist",
        nargs="*",
        default=[],
        metavar="PATH",
        help="Normalized paths to ignore. Empty by default: every entry is a known gap.",
    )
    parser.add_argument("--json-out", default=None, help="Optional path to write a JSON report.")
    parser.add_argument(
        "--quiet", action="store_true", help="Print only the failure lines, not the summary."
    )
    args = parser.parse_args(argv)

    report = scan({normalize_path(item) for item in args.allowlist})
    payload = json.dumps(report, indent=2)

    if args.json_out:
        out_path = Path(args.json_out)
        if not out_path.is_absolute():
            out_path = ROOT / out_path
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(payload + "\n", encoding="utf-8")

    if report["status"] == "PASS":
        if not args.quiet:
            print(
                f"frontend/backend paths verified: {report['matched_count']} calls across "
                f"{report['frontend_files_scanned']} files match "
                f"{report['backend_paths_normalized']} live routes"
            )
            if report["allowlisted_count"]:
                print(f"WARNING: {report['allowlisted_count']} path(s) are allowlisted")
        return 0

    print(payload)
    print(
        f"\nERROR: {report['unmatched_count']} frontend call(s) have no backend route "
        f"(file:line listed above).",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
